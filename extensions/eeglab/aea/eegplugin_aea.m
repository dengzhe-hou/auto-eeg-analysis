% EEGPLUGIN_AEA - Add the AEA study handoff to EEGLAB's Tools menu.
% Requires a configured AEA checkout and Python environment; see README.md.
function vers = eegplugin_aea(fig, try_strings, catch_strings)
vers = 'aea0.1.1';
addpath(fileparts(mfilename('fullpath')));
tools_menu = findobj(fig, 'tag', 'tools');
% EEGLAB disables the Tools parent before a dataset is loaded. Settings,
% launch and report must remain reachable during first-time setup.
set(tools_menu, 'UserData', 'startup:on;study:on');
menu = uimenu(tools_menu, 'Label', 'AEA', 'Tag', 'aea', ...
    'UserData', 'startup:on;study:off');
uimenu(menu, 'Label', 'Settings...', 'Tag', 'aea_settings', ...
    'Callback', 'pop_aea([], ''action'', ''configure'');', 'UserData', 'startup:on');
uimenu(menu, 'Label', 'Export current dataset and prepare study...', ...
    'Tag', 'aea_export', 'Callback', 'pop_aea(EEG, ''action'', ''export'');', ...
    'UserData', 'startup:off');
uimenu(menu, 'Label', 'Start AEA for exported study...', 'Tag', 'aea_launch', ...
    'Callback', 'pop_aea([], ''action'', ''launch'');', 'UserData', 'startup:on');
uimenu(menu, 'Label', 'Open study report...', 'Tag', 'aea_report', ...
    'Callback', 'pop_aea([], ''action'', ''report'');', 'UserData', 'startup:on');
uimenu(menu, 'Label', 'Getting started', 'Tag', 'aea_help', 'Separator', 'on', ...
    'Callback', 'web(''https://dengzhe-hou.github.io/auto-eeg-analysis/EEGLAB.html'', ''-browser'');', ...
    'UserData', 'startup:on');
end
