% AEA_PREPARE_MATLAB - Prepare an exported study using EEGLAB, without Python.
% No scientific computation, model call or approval is performed here.
function info = aea_prepare_matlab(project)
config = jsondecode(fileread(fullfile(project, 'AEA_BRIDGE_CONFIG.json')));
export = jsondecode(fileread(fullfile(project, 'EEGLAB_EXPORT.json')));
if ~strcmp(config.backend, 'matlab')
    error('AEA:Backend', 'This preparation function requires backend matlab.');
end
repository = config.repository;
if ~exist(fullfile(repository, 'AGENT_GUIDE.md'), 'file')
    error('AEA:Repository', 'Select an AEA checkout containing AGENT_GUIDE.md.');
end
if ~any(strcmp(config.client, {'codex', 'claude'}))
    error('AEA:Client', 'Choose codex or claude in AEA settings.');
end
recipe = config.recipe;
if ~strcmp(recipe, 'custom') && ~exist(fullfile(repository, 'recipes', recipe, 'RECIPE.md'), 'file')
    error('AEA:Recipe', 'Recipe not found: %s', recipe);
end
[folder, name, extension] = fileparts(fullfile(project, export.input_file));
EEG = pop_loadset('filename', [name extension], 'filepath', folder);
if EEG.nbchan ~= export.n_channels || EEG.pnts ~= export.n_samples_per_epoch || ...
        EEG.trials ~= export.n_epochs || EEG.srate ~= export.srate
    error('AEA:ImportMismatch', 'EEGLAB readback dimensions/rate differ from the export.');
end
runtime = struct('name', 'MATLAB', 'version', version, ...
    'executable', fullfile(matlabroot, 'bin', 'matlab'), ...
    'eeglab_path', fileparts(which('eeglab')));
if ispc, runtime.executable = [runtime.executable '.exe']; end
if exist('OCTAVE_VERSION', 'builtin')
    runtime.name = 'GNU Octave';
    runtime.executable = fullfile(OCTAVE_HOME(), 'bin', 'octave-cli');
end
header = struct('backend', 'matlab', 'reader', 'EEGLAB pop_loadset', ...
    'dataset_kind', export.dataset_kind, 'n_channels', EEG.nbchan, ...
    'n_samples_per_epoch', EEG.pnts, 'n_epochs', EEG.trials, 'sfreq', EEG.srate, ...
    'channel_names', {{EEG.chanlocs.labels}}, 'sample_unit', 'uV', ...
    'runtime', runtime, 'input_file', fullfile(project, export.input_file), ...
    'scope', 'Import agreement only; scientific choices need researcher confirmation.');
aea_write_json(fullfile(project, 'EEGLAB_IMPORT_CHECK.json'), header);
aea_write_json(fullfile(project, 'ENVIRONMENT.json'), struct('analysis_backend', 'matlab', ...
    'runtime', runtime, 'eeglab', struct('available', true, 'path', runtime.eeglab_path), ...
    'python_required', false, 'model_invoked', false));
brief = fullfile(project, 'DATASET_BRIEF.md');
if ~exist(brief, 'file')
    write_text(brief, sprintf(['# EEGLAB imported study\n\n' ...
        '- Input: `%s` (%s)\n- Shape: %d channels, %d samples, %d epochs\n' ...
        '- Sampling rate: %.17g Hz; epoch origin: %.17g s\n' ...
        '- Backend: MATLAB/EEGLAB; sample unit: microvolts (no V conversion)\n' ...
        '- Source processing: input/processing_history.txt\n' ...
        '- Events: input/events.json; latency is in one-based samples\n' ...
        '- Study question, participants, event meanings, channel types, prior processing,\n' ...
        '  ROI, windows, contrasts and statistics require researcher confirmation.\n' ...
        '- An export or recipe selection does not approve scientific parameters.\n'], ...
        export.input_file, export.dataset_kind, EEG.nbchan, EEG.pnts, EEG.trials, ...
        EEG.srate, export.epoch_tmin_s));
end
task = 'Choose relevant AEA skills for the researcher''s question.';
if ~strcmp(recipe, 'custom')
    task = sprintf('Read the selected recipe: %s. Its examples are not approved parameters.', ...
        fullfile(repository, 'recipes', recipe, 'RECIPE.md'));
end
request = sprintf(['Work on the EEGLAB-exported study at %s.\n' ...
    'Read %s and %s, then the relevant SKILL.md and linked procedures in full.\n' ...
    'Read the skill source files directly; native skill-directory links are optional.\n%s\n' ...
    'Read DATASET_BRIEF.md, EEGLAB_EXPORT.json, EEGLAB_IMPORT_CHECK.json,\n' ...
    'ENVIRONMENT.json, input/events.json and input/processing_history.txt.\n' ...
    'Analysis backend requested by the researcher: MATLAB/EEGLAB, not MNE.\n' ...
    'Use the recorded runtime executable and EEGLAB path in ENVIRONMENT.json.\n' ...
    'Generate study-local .m scripts and execute them with MATLAB -batch\n' ...
    '(or the recorded GNU Octave runtime when that is the actual environment).\n' ...
    'Do not require Python, MNE or MATLAB Engine for Python for this route.\n' ...
    'Keep scientific rules from the skills; record any MATLAB translation and its checks.\n' ...
    'A tested bounded epoched-ERP mean helper is at %s. It requires explicit\n' ...
    'condition epoch indices, ROI, time window and contrast; it does not preprocess.\n' ...
    'For other processing, consult the existing EEGLAB/FieldTrip templates and\n' ...
    'record actual capability/dependency checks. Do not claim every skill is ported.\n' ...
    'Preserve existing epochs, ICA metadata, source files and processing history.\n' ...
    'Do not refilter, rereference, refit ICA or reinterpret events without approval.\n' ...
    'Reuse an existing approved ANALYSIS_PLAN.md and its permissions. Otherwise\n' ...
    'inspect inputs, draft a plan and wait for researcher approval before its\n' ...
    'dependent scientific computations. Record unresolved choices and continue\n' ...
    'only independent authorized work. Unsupported steps require an explicit decision,\n' ...
    'not a silent switch to MNE or untested MATLAB equivalents.\n' ...
    'Keep the executed .m code, parameters, versions, numerical checks, figures\n' ...
    'and report with this study. Do not edit the AEA library.\n' ...
    'Write the HTML report to report-stage/report.html for EEGLAB to open.\n'], ...
    project, fullfile(repository, 'AGENT_GUIDE.md'), fullfile(repository, 'RESOURCE_INDEX.md'), ...
    task, fullfile(repository, 'extensions', 'eeglab', 'aea', 'aea_erp_mean.m'));
write_text(fullfile(project, 'AEA_REQUEST.md'), request);
aea_write_json(fullfile(project, 'AEA_HANDOFF.json'), struct( ...
    'state', 'ready_for_interactive_planning', 'backend', 'matlab', ...
    'scientific_plan_approved_by_export', false, 'client', config.client, ...
    'recipe', recipe, 'input_file', export.input_file, 'request_file', 'AEA_REQUEST.md', ...
    'report_file', 'report-stage/report.html', 'model_invoked_during_preparation', false));
info = struct('project', project, 'status', 'prepared', 'backend', 'matlab');
end

function write_text(path, text)
fid = fopen(path, 'w', 'n', 'UTF-8');
if fid < 0, error('AEA:WriteFailed', 'Cannot write %s', path); end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, '%s', text);
end
